#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从技能生成斜杠命令卡（约定优于配置：加技能 = 丢一个目录，不再需要手写卡片）。

为什么要有这个（2026-10-24，用户提的核心产品问题）：
    别人（Anthropic Agent Skills 规范）加技能只要 1 处 —— 一个带 frontmatter 的 `SKILL.md` 丢进
    skills 目录即可。我们之前加一个技能要动 5 处（SKILL.md / pack.json / trigger-probes /
    tasks 卡片 / 部署），等于每加一个技能都要改代码，这不叫产品。

做法：
    · 扫描 `Tool/skill/*/SKILL.md`（顶层目录 = 生效技能），用它的 `name` + `description`
      **自动生成** `Tool/prompts/tasks/<name>.md`（薄指针：指路 + 传参 + 无目标先问）。
    · 生成的卡带 `<!-- AUTO-GENERATED -->` 标记；**手写卡（无标记）永不被覆盖**。
    · 卡片内容不复制任何协议 —— 协议只在 SKILL.md 里有一份（避免第二事实源漂移）。

用法：
    python Tool/scripts/gen-commands.py            # 生成/更新
    python Tool/scripts/gen-commands.py --check     # 只检查是否最新（CI 用，退出码 1 = 有漂移）
"""
import argparse
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SKILL_DIR = os.path.join(ROOT, "Tool", "skill")
TASK_DIR = os.path.join(ROOT, "Tool", "prompts", "tasks")
MARK = "<!-- AUTO-GENERATED by Tool/scripts/gen-commands.py -->"

TPL = """{mark}
---
description: {desc}
argument-hint: "<目标路径或一句话需求>"
---

用 SEEP 的 **{name}** 域处理下面这件事：

目标/需求：`${{@:-（未给）}}`

**动作**：读 `@SEEP_ROOT@/Tool/skill/{name}/SKILL.md`，整篇读完再按它执行。
（若没给目标：先只问一句"目标是什么 / 想让我做到哪一步"，不要开始分析、不要写脚本。）
"""


def skills():
    out = []
    for d in sorted(os.listdir(SKILL_DIR)):
        p = os.path.join(SKILL_DIR, d, "SKILL.md")
        if not os.path.isfile(p):
            continue
        t = io.open(p, encoding="utf-8", errors="replace").read()
        m = re.search(r"^description:\s*(.+)$", t, re.M)
        if not m:
            out.append((d, None))
            continue
        desc = " ".join(m.group(1).strip().strip('"').split())
        out.append((d, desc))
    return out


def card_text(name, desc):
    # 描述压到 60 字内，别把整段描述塞进命令补全
    short = desc if len(desc) <= 60 else desc[:58] + "…"
    return TPL.format(mark=MARK, desc=short, name=name)


def main():
    ap = argparse.ArgumentParser(description="从技能自动生成斜杠命令卡")
    ap.add_argument("--check", action="store_true", help="只检查是否最新")
    a = ap.parse_args()

    os.makedirs(TASK_DIR, exist_ok=True)
    wrote, stale, skipped = [], [], []
    for name, desc in skills():
        if not desc:
            skipped.append(name + "(无 description)")
            continue
        path = os.path.join(TASK_DIR, name + ".md")
        text = card_text(name, desc)
        if os.path.isfile(path):
            old = io.open(path, encoding="utf-8", errors="replace").read()
            if MARK not in old:
                skipped.append(name + "(手写卡，保留)")
                continue
            if old == text:
                continue
            if a.check:
                stale.append(name)
                continue
        wrote.append(name)
        if not a.check:
            io.open(path, "w", encoding="utf-8", newline="\n").write(text)

    if a.check:
        if stale:
            print("命令卡不是最新：%s" % "、".join(stale))
            print("跑 python Tool/scripts/gen-commands.py 重新生成")
            return 1
        print("命令卡已是最新（%d 个技能）" % len(skills()))
        return 0

    print("生成/更新 %d 张卡：%s" % (len(wrote), "、".join(wrote) or "（无变化）"))
    if skipped:
        print("跳过：%s" % "、".join(skipped))
    return 0


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    sys.exit(main())
