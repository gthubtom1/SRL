#!/usr/bin/env python3
"""Derive retrieval aliases from the existing normalizer; never rewrite requests.

The historical filename/output name remain for maintenance scripts. The output
contains from/route_terms only and is not loaded by the HTTP relay. Invalid or
missing source data fails validation; there is no second embedded word table.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
NORMALIZE_SOURCE = os.path.join(REPO_ROOT, "Tool", "config", "input-normalize.json")
OUTPUT = os.path.join(HERE, "sensitive-rules.json")
spec = importlib.util.spec_from_file_location("rewrite_parity", os.path.join(HERE, "..", "rewrite-route-parity.py"))
normalizer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(normalizer)


def extract_rules(normalize_path: str = NORMALIZE_SOURCE) -> list[dict]:
    pairs, _, problems = normalizer.load_normalize(normalize_path)
    if problems:
        raise ValueError("; ".join(problems))
    return pairs


def validate(rules: list[dict]) -> list[str]:
    return normalizer.validate_pairs(rules)


def build_payload(rules: list[dict]) -> dict:
    return {"schema": 2, "purpose": "retrieval-only",
            "generatedFrom": "Tool/config/input-normalize.json",
            "_comment": "Generated by extract-rules.py; aliases never replace original material or route input.",
            "ruleCount": len(rules), "rules": rules}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        payload = build_payload(extract_rules())
        serialized = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
        if args.check:
            with open(OUTPUT, encoding="utf-8") as fh:
                if fh.read() != serialized:
                    raise ValueError("derived aliases differ; run extract-rules.py")
        else:
            with open(OUTPUT, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(serialized)
    except (OSError, ValueError) as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        return 1
    print(f"[OK] {payload['ruleCount']} retrieval alias entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
